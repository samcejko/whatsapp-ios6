# Generates core/wa_mlow_rc_kat.c (the range-coder known-answer vectors) from meowcaller's rc_vectors.json.
# (meowcaller is MIT.) The vectors are embedded so the CI self-test needs no data file at run time.
param(
    [Parameter(Mandatory = $true)][string]$Vectors,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_rc_kat.c')
)
$ErrorActionPreference = 'Stop'
$j = Get-Content -LiteralPath $Vectors -Raw | ConvertFrom-Json

function HexBytes([string]$hex) {
    $n = $hex.Length / 2
    $a = New-Object int[] $n
    for ($i = 0; $i -lt $n; $i++) { $a[$i] = [Convert]::ToInt32($hex.Substring($i * 2, 2), 16) }
    return $a
}

$bytes = HexBytes $j.bytesHex
$cdfBytes = HexBytes $j.cdfBytesHex
$icdf = [Convert]::FromBase64String($j.icdf)   # 6 bytes

$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }

W '// Generated by tools/gen-rc-kat.ps1 - do not edit. Range-coder KAT vectors from meowcaller (MIT).'
W '#include <stdint.h>'
W ''
W ("const int wa_rc_kat_bytes_len = {0};" -f $bytes.Count)
W ('const uint8_t wa_rc_kat_bytes[] = { ' + (($bytes | ForEach-Object { $_ }) -join ',') + ' };')
W ('const uint8_t wa_rc_kat_icdf[6] = { ' + (($icdf | ForEach-Object { [int]$_ }) -join ',') + ' };')
W ''
W ("const int wa_rc_kat_ops_len = {0};" -f $j.ops.Count)
W 'const uint32_t wa_rc_kat_ops[][3] = {'
foreach ($o in $j.ops) { W ("{{{0}u,{1}u,{2}u}}," -f [uint32]$o.kind, [uint32]$o.a, [uint32]$o.b) }
W '};'
W ''
W ("const int wa_rc_kat_cdf_bytes_len = {0};" -f $cdfBytes.Count)
W ('const uint8_t wa_rc_kat_cdf_bytes[] = { ' + (($cdfBytes | ForEach-Object { $_ }) -join ',') + ' };')
W ''
# flatten cdfTables
$flat = New-Object System.Collections.Generic.List[int]
$off = New-Object System.Collections.Generic.List[int]
$tablen = New-Object System.Collections.Generic.List[int]
foreach ($t in $j.cdfTables) {
    $off.Add($flat.Count)
    $tablen.Add($t.Count)
    foreach ($v in $t) { $flat.Add([int]$v) }
}
W ("const int wa_rc_kat_cdf_ntables = {0};" -f $j.cdfTables.Count)
W ('const uint16_t wa_rc_kat_cdf_flat[] = { ' + ($flat -join ',') + ' };')
W ('const int wa_rc_kat_cdf_off[] = { ' + ($off -join ',') + ' };')
W ('const int wa_rc_kat_cdf_tablen[] = { ' + ($tablen -join ',') + ' };')
W ''
W ("const int wa_rc_kat_cdf_ops_len = {0};" -f $j.cdfOps.Count)
W 'const uint32_t wa_rc_kat_cdf_ops[][2] = {'
foreach ($o in $j.cdfOps) { W ("{{{0}u,{1}u}}," -f [uint32]$o.kind, [uint32]$o.a) }
W '};'

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} ops, {2} cdf tables, {3} cdf ops, {4} bytes)" -f $Out, $j.ops.Count, $j.cdfTables.Count, $j.cdfOps.Count, $bytes.Count)
