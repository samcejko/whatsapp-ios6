# Generates core/wa_mlow_lsf_tab.c: the runtime-built LSF CDF tables (from meowcaller smpl_tables.json) and the
# LSF decode KAT (frames + expected indices from lsf_vectors.json). Both MIT.
param(
    [Parameter(Mandatory = $true)][string]$Tables,
    [Parameter(Mandatory = $true)][string]$Vectors,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_lsf_tab.c')
)
$ErrorActionPreference = 'Stop'
$t = Get-Content -LiteralPath $Tables -Raw | ConvertFrom-Json
$v = Get-Content -LiteralPath $Vectors -Raw | ConvertFrom-Json

$flat = New-Object System.Collections.Generic.List[int]
$off = New-Object System.Collections.Generic.List[int]
$len = New-Object System.Collections.Generic.List[int]
function AddCdf($arr) {
    $off.Add($flat.Count); $len.Add($arr.Count)
    foreach ($x in $arr) { $flat.Add([int]$x) }
}

# order: sel[0..2], grid{match1,match1_alt,match0,match0_alt}, extra, then stage2[s1][cfg][grid][coeff]
foreach ($row in $t.lsf_sel) { AddCdf $row }                 # indices 0,1,2
AddCdf $t.lsf_grid.match1                                     # 3
AddCdf $t.lsf_grid.match1_alt                                 # 4
AddCdf $t.lsf_grid.match0                                     # 5
AddCdf $t.lsf_grid.match0_alt                                 # 6
AddCdf $t.lsf_extra                                           # 7
$st2base = $off.Count
foreach ($s1 in $t.lsf_stage2) { foreach ($cfg in $s1) { foreach ($g in $cfg) { foreach ($coeff in $g) { AddCdf $coeff } } } }

$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
W '// Generated by tools/gen-lsf.ps1 - do not edit. MLow LSF CDF tables + KAT (meowcaller smpl_tables/lsf_vectors, MIT).'
W '#include <stdint.h>'
W ('const uint16_t wa_lsf_cdf[] = { ' + ($flat -join ',') + ' };')
W ('const int wa_lsf_off[] = { ' + ($off -join ',') + ' };')
W ('const int wa_lsf_len[] = { ' + ($len -join ',') + ' };')
W ("const int wa_lsf_stage2_base = {0};" -f $st2base)   # index of stage2[0][0][0][0]; stride for [s1][cfg][grid][coeff]
W ("const int wa_lsf_cfg_count = {0};" -f $t.lsf_stage2[0].Count)
W ("const int wa_lsf_grid_count = {0};" -f $t.lsf_stage2[0][0].Count)
W '// stage2 cdf index = base + ((s1*cfg_count + cfg)*grid_count + grid)*16 + coeff'
W ''
# KAT
W ("const int wa_lsf_kat_len = {0};" -f $v.Count)
W 'const int wa_lsf_kat_framelen[] = {'
$frames = New-Object System.Collections.Generic.List[int]
$frameoff = New-Object System.Collections.Generic.List[int]
foreach ($rec in $v) {
    $h = $rec.frame; $fl = $h.Length / 2
    $frameoff.Add($frames.Count)
    for ($i = 0; $i -lt $fl; $i++) { $frames.Add([Convert]::ToInt32($h.Substring($i*2,2),16)) }
    W ("$fl,")
}
W '};'
W ('const int wa_lsf_kat_frameoff[] = { ' + ($frameoff -join ',') + ' };')
W ('const uint8_t wa_lsf_kat_frames[] = { ' + ($frames -join ',') + ' };')
W 'const int wa_lsf_kat_stage1[] = {'; W ((($v | ForEach-Object { [int]$_.stage1 }) -join ',')); W '};'
W 'const int wa_lsf_kat_grid[] = {'; W ((($v | ForEach-Object { [int]$_.grid }) -join ',')); W '};'
W 'const int wa_lsf_kat_extra[] = {'; W ((($v | ForEach-Object { [int]$_.extra }) -join ',')); W '};'
W 'const int wa_lsf_kat_stage2[][16] = {'
foreach ($rec in $v) { W ('{ ' + (($rec.stage2 | ForEach-Object { [int]$_ }) -join ',') + ' },') }
W '};'
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} cdfs, stage2 base {2}, {3} KAT frames)" -f $Out, $off.Count, $st2base, $v.Count)
