# Generates core/wa_tokens.c (the binary-node dictionaries) from a tokens.json with
#   { "single_byte": [236 strings], "double_byte": [[256], [256], [256], [256]] }
# (the dictionary version 3 tables, as published in whatsapp-rust wacore/binary/src/tokens.json, MIT).
param(
    [Parameter(Mandatory = $true)][string]$TokensJson,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_tokens.c')
)
$ErrorActionPreference = 'Stop'
$t = Get-Content -LiteralPath $TokensJson -Raw | ConvertFrom-Json

function Quote([string]$s) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append('"')
    foreach ($ch in $s.ToCharArray()) {
        $c = [int]$ch
        if ($ch -eq '"' -or $ch -eq '\') { [void]$sb.Append('\').Append($ch) }
        elseif ($c -lt 0x20 -or $c -gt 0x7e) { [void]$sb.AppendFormat('\x{0:x2}""', $c) }
        else { [void]$sb.Append($ch) }
    }
    [void]$sb.Append('"')
    $sb.ToString()
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// Generated by tools/gen-tokens.ps1 - do not edit. WhatsApp binary XML dictionaries, version 3.')
$lines.Add('// Token tables from whatsapp-rust (MIT, Copyright (c) 2025 Joao Lucas de Oliveira Lopes).')
$lines.Add('#include "wa_node.h"')
$lines.Add('')
$lines.Add("const int wa_single_token_count = $($t.single_byte.Count);")
$lines.Add('const char *const wa_single_tokens[] = {')
foreach ($s in $t.single_byte) { $lines.Add("    $(Quote $s),") }
$lines.Add('};')
$lines.Add('')
$lines.Add('const char *const wa_double_tokens[4][256] = {')
foreach ($d in $t.double_byte) {
    $lines.Add('    {')
    foreach ($s in $d) { $lines.Add("        $(Quote $s),") }
    $lines.Add('    },')
}
$lines.Add('};')
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath (Split-Path $Out)).Path + '\' + (Split-Path $Out -Leaf), $lines, $utf8)
Write-Host "wrote $Out ($($t.single_byte.Count) single, $($t.double_byte.Count) x 256 double)"
