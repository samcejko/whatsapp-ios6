# Generates core/wa_mlow_gains_kat.c from meowcaller gains_vectors.json (frame hex + gain_q[4] + nrg_res[4]).
param(
    [Parameter(Mandatory = $true)][string]$Vectors,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_gains_kat.c')
)
$ErrorActionPreference = 'Stop'
$v = Get-Content -LiteralPath $Vectors -Raw | ConvertFrom-Json
$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
W '// Generated by tools/gen-gains.ps1 - do not edit. MLow gains KAT (meowcaller gains_vectors.json, MIT).'
W '#include <stdint.h>'
W ("const int wa_mlow_gains_kat_len = {0};" -f $v.Count)

$frames = New-Object System.Collections.Generic.List[int]
$frameoff = New-Object System.Collections.Generic.List[int]
$framelen = New-Object System.Collections.Generic.List[int]
$gainLines = New-Object System.Collections.Generic.List[string]
$nrgLines = New-Object System.Collections.Generic.List[string]
foreach ($rec in $v) {
    $h = $rec.frame; $fl = $h.Length / 2
    $frameoff.Add($frames.Count); $framelen.Add($fl)
    for ($i = 0; $i -lt $fl; $i++) { $frames.Add([Convert]::ToInt32($h.Substring($i * 2, 2), 16)) }
    $gainLines.Add('{ ' + (($rec.gain_q | ForEach-Object { [int]$_ }) -join ',') + ' },')
    $nrgLines.Add('{ ' + (($rec.nrg_res | ForEach-Object { [int]$_ }) -join ',') + ' },')
}
W ('const int wa_mlow_gains_kat_framelen[] = { ' + ($framelen -join ',') + ' };')
W ('const int wa_mlow_gains_kat_frameoff[] = { ' + ($frameoff -join ',') + ' };')
W ('const uint8_t wa_mlow_gains_kat_frames[] = { ' + ($frames -join ',') + ' };')
W 'const int32_t wa_mlow_gains_kat_gainq[][4] = {'
foreach ($l in $gainLines) { W $l }
W '};'
W 'const int32_t wa_mlow_gains_kat_nrgres[][4] = {'
foreach ($l in $nrgLines) { W $l }
W '};'
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} frames)" -f $Out, $v.Count)
