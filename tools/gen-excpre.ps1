# Generates core/wa_mlow_excpre_kat.c from meowcaller inbound_capture_frames.json (hex frames, replayed in
# order so the ACB/LSF/pitch state carries) + exc_pre_lags.json (expected per-subframe excitation as sparse
# nonzero (pos,val) pairs). Float vals stored as IEEE-754 u32 bits; compared at 2e-5 in C.
param(
    [Parameter(Mandatory = $true)][string]$FramesPath,
    [Parameter(Mandatory = $true)][string]$LagsPath,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_excpre_kat.c')
)
$ErrorActionPreference = 'Stop'
$frames = Get-Content -LiteralPath $FramesPath -Raw | ConvertFrom-Json
$recs = Get-Content -LiteralPath $LagsPath -Raw | ConvertFrom-Json
$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
function FB($x) { [BitConverter]::ToUInt32([BitConverter]::GetBytes([float]$x), 0) }

W '// Generated by tools/gen-excpre.ps1 - do not edit. MLow exc_pre KAT (meowcaller inbound_capture_frames.json'
W '// + exc_pre_lags.json, MIT). Frames replayed in order; expected excitation as sparse nonzero pairs.'
W '#include <stdint.h>'

# frames
$fbytes = New-Object System.Collections.Generic.List[int]
$foff = New-Object System.Collections.Generic.List[int]
$flen = New-Object System.Collections.Generic.List[int]
foreach ($h in $frames) {
    $foff.Add($fbytes.Count)
    $n = [int]($h.Length / 2)
    $flen.Add($n)
    for ($i = 0; $i -lt $n; $i++) { $fbytes.Add([Convert]::ToInt32($h.Substring($i * 2, 2), 16)) }
}
W ("const int wa_mlow_excpre_nframes = {0};" -f $frames.Count)
W ('const int wa_mlow_excpre_frameoff[] = { ' + ($foff -join ',') + ' };')
W ('const int wa_mlow_excpre_framelen[] = { ' + ($flen -join ',') + ' };')
W ('const uint8_t wa_mlow_excpre_frames[] = { ' + ($fbytes -join ',') + ' };')

# records
$pk = New-Object System.Collections.Generic.List[int]
$fr = New-Object System.Collections.Generic.List[int]
$sf = New-Object System.Collections.Generic.List[int]
$nzoff = New-Object System.Collections.Generic.List[int]
$nzcnt = New-Object System.Collections.Generic.List[int]
$nzpos = New-Object System.Collections.Generic.List[int]
$nzval = New-Object System.Collections.Generic.List[uint32]
foreach ($r in $recs) {
    $pk.Add([int]$r.packet); $fr.Add([int]$r.frame); $sf.Add([int]$r.sf)
    $nzoff.Add($nzpos.Count)
    $c = 0
    if ($null -ne $r.nz) { foreach ($pair in $r.nz) { $nzpos.Add([int]$pair[0]); $nzval.Add([uint32](FB $pair[1])); $c++ } }
    $nzcnt.Add($c)
}
W ("const int wa_mlow_excpre_nrecs = {0};" -f $recs.Count)
W ('const int wa_mlow_excpre_rec_packet[] = { ' + ($pk -join ',') + ' };')
W ('const int wa_mlow_excpre_rec_frame[] = { ' + ($fr -join ',') + ' };')
W ('const int wa_mlow_excpre_rec_sf[] = { ' + ($sf -join ',') + ' };')
W ('const int wa_mlow_excpre_rec_nzoff[] = { ' + ($nzoff -join ',') + ' };')
W ('const int wa_mlow_excpre_rec_nzcount[] = { ' + ($nzcnt -join ',') + ' };')
W ('const int wa_mlow_excpre_nzpos[] = { ' + ($nzpos -join ',') + ' };')
W ('const uint32_t wa_mlow_excpre_nzval[] = { ' + (($nzval | ForEach-Object { '0x{0:x8}u' -f $_ }) -join ',') + ' };')

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} frames, {2} records, {3} nz pairs)" -f $Out, $frames.Count, $recs.Count, $nzpos.Count)
