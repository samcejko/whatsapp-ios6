# Generates core/wa_mlow_postfilter_kat.c from meowcaller hp_postfilter_vectors.raw + harm_postfilter_vectors.raw.
# HP frames are self-contained (each seeds its own state) so a subset is embedded; harm packets carry state so
# the FIRST NHarm packets are embedded in order. Floats stored as IEEE-754 u32 bits; checked to the i16 LSB in C.
param(
    [Parameter(Mandatory = $true)][string]$HpRaw,
    [Parameter(Mandatory = $true)][string]$HarmRaw,
    [int]$NHp = 50,
    [int]$NHarm = 12,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_postfilter_kat.c')
)
$ErrorActionPreference = 'Stop'
$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
function HEX($u) { '0x{0:x8}u' -f $u }

# --- HP ---
$hp = [System.IO.File]::ReadAllBytes($HpRaw)
$o = 0
function RdI([byte[]]$b) { $v = [BitConverter]::ToInt32($b, $script:o); $script:o += 4; return $v }
function RdU([byte[]]$b) { $v = [BitConverter]::ToUInt32($b, $script:o); $script:o += 4; return $v }
$hpCount = RdI $hp
$n = [Math]::Min($NHp, $hpCount)
$lags = @(); $lo1 = @(); $lo2 = @(); $hpst = @(); $lagold = @(); $xold = @(); $coefma = @(); $coefar = @(); $ypre = @(); $ypost = @()
for ($f = 0; $f -lt $hpCount; $f++) {
    [void](RdI $hp); [void](RdI $hp)           # packet, frame
    $L = for ($i = 0; $i -lt 8; $i++) { RdU $hp }
    $a1 = RdU $hp; $a2 = RdU $hp
    $H = for ($i = 0; $i -lt 4; $i++) { RdU $hp }
    $lg = RdU $hp
    $xo = for ($i = 0; $i -lt 320; $i++) { RdU $hp }
    $cm = for ($i = 0; $i -lt 3; $i++) { RdU $hp }
    $ca = for ($i = 0; $i -lt 3; $i++) { RdU $hp }
    $yp = for ($i = 0; $i -lt 320; $i++) { RdU $hp }
    $yq = for ($i = 0; $i -lt 320; $i++) { RdU $hp }
    if ($f -lt $n) {
        $lags += , @($L); $lo1 += $a1; $lo2 += $a2; $hpst += , @($H); $lagold += $lg
        $xold += , @($xo); $coefma += , @($cm); $coefar += , @($ca); $ypre += , @($yp); $ypost += , @($yq)
    }
}

# --- harm ---
$hm = [System.IO.File]::ReadAllBytes($HarmRaw)
$o = 0
$harmCount = RdI $hm
$m = [Math]::Min($NHarm, $harmCount)
$plens = @(); $nlagsA = @(); $nbr = @(); $lagoff = @(); $lagflat = @(); $sigoff = @(); $inpflat = @(); $coutflat = @()
for ($p = 0; $p -lt $m; $p++) {
    [void](RdI $hm)                            # packet
    $plen = RdI $hm; $nl = RdI $hm; $nb = RdU $hm
    $lagoff += $lagflat.Count
    for ($i = 0; $i -lt $nl; $i++) { $lagflat += (RdU $hm) }
    $sigoff += $inpflat.Count
    for ($i = 0; $i -lt $plen; $i++) { $inpflat += (RdU $hm) }
    for ($i = 0; $i -lt $plen; $i++) { $coutflat += (RdU $hm) }
    $plens += $plen; $nlagsA += $nl; $nbr += $nb
}

W '// Generated by tools/gen-postfilter.ps1 - do not edit. MLow postfilter KAT (meowcaller *_postfilter_vectors.raw, MIT).'
W '#include <stdint.h>'
W ("const int wa_mlow_hppf_kat_len = {0};" -f $n)
W ('const uint32_t wa_mlow_hppf_kat_lags[][8] = {'); foreach ($r in $lags) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'
W ('const uint32_t wa_mlow_hppf_kat_lo1[] = { ' + (($lo1 | ForEach-Object { HEX $_ }) -join ',') + ' };')
W ('const uint32_t wa_mlow_hppf_kat_lo2[] = { ' + (($lo2 | ForEach-Object { HEX $_ }) -join ',') + ' };')
W ('const uint32_t wa_mlow_hppf_kat_hp[][4] = {'); foreach ($r in $hpst) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'
W ('const uint32_t wa_mlow_hppf_kat_lagold[] = { ' + (($lagold | ForEach-Object { HEX $_ }) -join ',') + ' };')
W ('const uint32_t wa_mlow_hppf_kat_xold[][320] = {'); foreach ($r in $xold) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'
W ('const uint32_t wa_mlow_hppf_kat_coefma[][3] = {'); foreach ($r in $coefma) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'
W ('const uint32_t wa_mlow_hppf_kat_coefar[][3] = {'); foreach ($r in $coefar) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'
W ('const uint32_t wa_mlow_hppf_kat_ypre[][320] = {'); foreach ($r in $ypre) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'
W ('const uint32_t wa_mlow_hppf_kat_ypost[][320] = {'); foreach ($r in $ypost) { W ('{ ' + (($r | ForEach-Object { HEX $_ }) -join ',') + ' },') }; W '};'

W ("const int wa_mlow_harmpf_kat_len = {0};" -f $m)
W ('const int wa_mlow_harmpf_kat_plen[] = { ' + ($plens -join ',') + ' };')
W ('const int wa_mlow_harmpf_kat_nlags[] = { ' + ($nlagsA -join ',') + ' };')
W ('const uint32_t wa_mlow_harmpf_kat_nbr[] = { ' + (($nbr | ForEach-Object { HEX $_ }) -join ',') + ' };')
W ('const int wa_mlow_harmpf_kat_lagoff[] = { ' + ($lagoff -join ',') + ' };')
W ('const uint32_t wa_mlow_harmpf_kat_lags[] = { ' + (($lagflat | ForEach-Object { HEX $_ }) -join ',') + ' };')
W ('const int wa_mlow_harmpf_kat_sigoff[] = { ' + ($sigoff -join ',') + ' };')
W ('const uint32_t wa_mlow_harmpf_kat_inp[] = { ' + (($inpflat | ForEach-Object { HEX $_ }) -join ',') + ' };')
W ('const uint32_t wa_mlow_harmpf_kat_cout[] = { ' + (($coutflat | ForEach-Object { HEX $_ }) -join ',') + ' };')

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0}: HP {1}/{2} frames, harm {3}/{4} packets" -f $Out, $n, $hpCount, $m, $harmCount)
