# Generates core/wa_mlow_gennoise_kat.c from meowcaller gennoise_vectors.json. Floats are embedded as their
# IEEE-754 uint32 bit patterns so inputs reproduce bit-exactly; expected noise is compared at 1e-6 in C.
param(
    [Parameter(Mandatory = $true)][string]$Vectors,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_gennoise_kat.c')
)
$ErrorActionPreference = 'Stop'
$v = Get-Content -LiteralPath $Vectors -Raw | ConvertFrom-Json
$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
function FB($x) { [BitConverter]::ToUInt32([BitConverter]::GetBytes([float]$x), 0) }     # float -> u32 bits
function Arr($name, $vals) { W ("const uint32_t $name" + "[] = { " + (($vals | ForEach-Object { '0x{0:x8}u' -f (FB $_) }) -join ',') + ' };') }
function IArr($name, $vals) { W ("const int32_t $name" + "[] = { " + (($vals -join ',')) + ' };') }
function Arr2($name, $cols, $rows) { W "const uint32_t $name[][$cols] = {"; foreach ($r in $rows) { W ('{ ' + (($r | ForEach-Object { '0x{0:x8}u' -f (FB $_) }) -join ',') + ' },') }; W '};' }

W '// Generated by tools/gen-gennoise.ps1 - do not edit. MLow gennoise KAT (meowcaller gennoise_vectors.json, MIT).'
W '// Floats stored as IEEE-754 u32 bit patterns (exact inputs); noise checked at 1e-6.'
W '#include <stdint.h>'
W ("const int wa_mlow_gennoise_kat_len = {0};" -f $v.Count)

IArr 'wa_mlow_gennoise_kat_voiced'   ($v | ForEach-Object { [int]$_.voiced })
IArr 'wa_mlow_gennoise_kat_sfpulses' ($v | ForEach-Object { [int]$_.sf_pulses })
IArr 'wa_mlow_gennoise_kat_fcbgidx'  ($v | ForEach-Object { [int]$_.fcbg_idx })
Arr  'wa_mlow_gennoise_kat_nrgres'   ($v | ForEach-Object { $_.nrgres })
Arr  'wa_mlow_gennoise_kat_normbr'   ($v | ForEach-Object { $_.norm_br })
IArr 'wa_mlow_gennoise_kat_seedout'  ($v | ForEach-Object { [int]$_.seed_out })

# ng_in
Arr  'wa_mlow_gennoise_kat_in_envsmth' ($v | ForEach-Object { $_.ng_in.env_smth })
Arr  'wa_mlow_gennoise_kat_in_envlast' ($v | ForEach-Object { $_.ng_in.env_last })
Arr2 'wa_mlow_gennoise_kat_in_osuv' 2  ($v | ForEach-Object { ,@($_.ng_in.out_state_uv) })
Arr2 'wa_mlow_gennoise_kat_in_osv'  2  ($v | ForEach-Object { ,@($_.ng_in.out_state_v) })
Arr2 'wa_mlow_gennoise_kat_in_corr' 3  ($v | ForEach-Object { ,@($_.ng_in.corr_smth) })
Arr2 'wa_mlow_gennoise_kat_in_shape' 2 ($v | ForEach-Object { ,@($_.ng_in.shape_state) })
IArr 'wa_mlow_gennoise_kat_in_prevvoiced' ($v | ForEach-Object { [int]$_.ng_in.prev_voiced })
IArr 'wa_mlow_gennoise_kat_in_sinceuv'    ($v | ForEach-Object { [int]$_.ng_in.since_unvoiced })
IArr 'wa_mlow_gennoise_kat_in_seed'       ($v | ForEach-Object { [int]$_.ng_in.rand_seed })

# ng_out (checked fields)
Arr  'wa_mlow_gennoise_kat_out_envlast' ($v | ForEach-Object { $_.ng_out.env_last })
Arr2 'wa_mlow_gennoise_kat_out_osuv' 2  ($v | ForEach-Object { ,@($_.ng_out.out_state_uv) })
Arr2 'wa_mlow_gennoise_kat_out_osv'  2  ($v | ForEach-Object { ,@($_.ng_out.out_state_v) })

# arrays
Arr2 'wa_mlow_gennoise_kat_excpre' 80 ($v | ForEach-Object { ,@($_.exc_pre) })
Arr2 'wa_mlow_gennoise_kat_lsf'    16 ($v | ForEach-Object { ,@($_.lsf) })
Arr2 'wa_mlow_gennoise_kat_noise'  80 ($v | ForEach-Object { ,@($_.noise) })

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} records)" -f $Out, $v.Count)
