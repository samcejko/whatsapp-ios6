# Inflates meowcaller mlow/pitch_seed.bin (zlib) and emits core/wa_mlow_pitch_seed.c with the raw inflated
# protobuf blob (the pitch lag/contour seed: blocksegs bitstream + index maps + DCMFs). The C side parses +
# expands it at init (wa_mlow_pitch.c), mirroring pitch_seed.go buildContourWindow. MIT (meowcaller/whatsapp-rust).
param(
    [Parameter(Mandatory = $true)][string]$Seed,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_pitch_seed.c')
)
$ErrorActionPreference = 'Stop'
$blob = [System.IO.File]::ReadAllBytes($Seed)
$inner = New-Object byte[] ($blob.Length - 2)
[Array]::Copy($blob, 2, $inner, 0, $blob.Length - 2)
$ms = New-Object System.IO.MemoryStream(, $inner)
$ds = New-Object System.IO.Compression.DeflateStream($ms, [System.IO.Compression.CompressionMode]::Decompress)
$outMs = New-Object System.IO.MemoryStream
$ds.CopyTo($outMs); $ds.Close()
$raw = $outMs.ToArray()

$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
W '// Generated by tools/gen-pitch-seed.ps1 - do not edit. Inflated MLow pitch_seed protobuf ROM'
W '// (meowcaller mlow/pitch_seed.bin, MIT). Parsed + expanded at init by wa_mlow_pitch.c.'
W '#include <stdint.h>'
W '#include <stddef.h>'
W ("const int wa_mlow_pitch_seed_len = {0};" -f $raw.Length)
W 'const uint8_t wa_mlow_pitch_seed[] = {'
$line = '    '
for ($i = 0; $i -lt $raw.Length; $i++) {
    $line += ('{0},' -f $raw[$i])
    if (($i % 20) -eq 19) { W $line; $line = '    ' }
}
if ($line.Trim().Length -gt 0) { W $line }
W '};'
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} inflated bytes)" -f $Out, $raw.Length)
