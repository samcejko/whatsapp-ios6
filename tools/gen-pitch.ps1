# Generates core/wa_mlow_pitch_kat.c from meowcaller pitch_vectors.json
# (frame hex + lag + contour + gain_idx[4] + filt_idx[4] + int_lag_q6[4]).
param(
    [Parameter(Mandatory = $true)][string]$Vectors,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_pitch_kat.c')
)
$ErrorActionPreference = 'Stop'
$v = Get-Content -LiteralPath $Vectors -Raw | ConvertFrom-Json
$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
W '// Generated by tools/gen-pitch.ps1 - do not edit. MLow pitch KAT (meowcaller pitch_vectors.json, MIT).'
W '#include <stdint.h>'
W ("const int wa_mlow_pitch_kat_len = {0};" -f $v.Count)

$frames = New-Object System.Collections.Generic.List[int]
$frameoff = New-Object System.Collections.Generic.List[int]
$framelen = New-Object System.Collections.Generic.List[int]
$lag = New-Object System.Collections.Generic.List[int]
$contour = New-Object System.Collections.Generic.List[int]
$gainLines = New-Object System.Collections.Generic.List[string]
$filtLines = New-Object System.Collections.Generic.List[string]
$ilagLines = New-Object System.Collections.Generic.List[string]
foreach ($rec in $v) {
    $h = $rec.frame; $fl = $h.Length / 2
    $frameoff.Add($frames.Count); $framelen.Add($fl)
    for ($i = 0; $i -lt $fl; $i++) { $frames.Add([Convert]::ToInt32($h.Substring($i * 2, 2), 16)) }
    $lag.Add([int]$rec.lag); $contour.Add([int]$rec.contour)
    $gainLines.Add('{ ' + (($rec.gain_idx | ForEach-Object { [int]$_ }) -join ',') + ' },')
    $filtLines.Add('{ ' + (($rec.filt_idx | ForEach-Object { [int]$_ }) -join ',') + ' },')
    $ilagLines.Add('{ ' + (($rec.int_lag_q6 | ForEach-Object { [int]$_ }) -join ',') + ' },')
}
W ('const int wa_mlow_pitch_kat_framelen[] = { ' + ($framelen -join ',') + ' };')
W ('const int wa_mlow_pitch_kat_frameoff[] = { ' + ($frameoff -join ',') + ' };')
W ('const uint8_t wa_mlow_pitch_kat_frames[] = { ' + ($frames -join ',') + ' };')
W ('const int32_t wa_mlow_pitch_kat_lag[] = { ' + ($lag -join ',') + ' };')
W ('const int32_t wa_mlow_pitch_kat_contour[] = { ' + ($contour -join ',') + ' };')
W 'const int32_t wa_mlow_pitch_kat_gainidx[][4] = {'
foreach ($l in $gainLines) { W $l }
W '};'
W 'const int32_t wa_mlow_pitch_kat_filtidx[][4] = {'
foreach ($l in $filtLines) { W $l }
W '};'
W 'const int32_t wa_mlow_pitch_kat_ilagq6[][4] = {'
foreach ($l in $ilagLines) { W $l }
W '};'
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} frames)" -f $Out, $v.Count)
