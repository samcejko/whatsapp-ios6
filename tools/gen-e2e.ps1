# Generates core/wa_mlow_e2e_kat.c from meowcaller ref_usesmpl_expected.raw (int16 LE PCM, the libopus useSmpl
# reference the whole decoded capture stream is correlated against). Embedded as an int16 array.
param(
    [Parameter(Mandatory = $true)][string]$Raw,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_e2e_kat.c')
)
$ErrorActionPreference = 'Stop'
$b = [System.IO.File]::ReadAllBytes($Raw)
$n = [int]($b.Length / 2)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/gen-e2e.ps1 - do not edit. MLow e2e reference PCM')
[void]$sb.AppendLine('// (meowcaller ref_usesmpl_expected.raw, int16 LE, MIT).')
[void]$sb.AppendLine('#include <stdint.h>')
[void]$sb.AppendLine(("const int wa_mlow_e2e_ref_len = {0};" -f $n))
[void]$sb.AppendLine('const int16_t wa_mlow_e2e_ref[] = {')
$line = New-Object System.Text.StringBuilder
for ($i = 0; $i -lt $n; $i++) {
    $v = [BitConverter]::ToInt16($b, $i * 2)
    [void]$line.Append($v); [void]$line.Append(',')
    if (($i % 24) -eq 23) { [void]$sb.AppendLine($line.ToString()); $line.Clear() | Out-Null }
}
if ($line.Length -gt 0) { [void]$sb.AppendLine($line.ToString()) }
[void]$sb.AppendLine('};')
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} samples)" -f $Out, $n)
