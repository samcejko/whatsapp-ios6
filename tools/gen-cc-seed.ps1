# Inflates meowcaller mlow/cc_seed.bin (zlib) and emits core/wa_mlow_cc_seed.c with the raw
# inflated protobuf blob (the DCMF "ROM" for the nrgres/gains/LTP/pulse-count tables). The C side
# parses this blob at init (parseProto) and expands the DCMFs, mirroring cc_tables.go build().
# cc_seed.bin is MIT (meowcaller / whatsapp-rust). We embed only the compact seed, not expanded tables.
param(
    [Parameter(Mandatory = $true)][string]$Seed,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_cc_seed.c')
)
$ErrorActionPreference = 'Stop'
$blob = [System.IO.File]::ReadAllBytes($Seed)
$inner = New-Object byte[] ($blob.Length - 2)   # strip 2-byte zlib header -> raw deflate
[Array]::Copy($blob, 2, $inner, 0, $blob.Length - 2)
$ms = New-Object System.IO.MemoryStream(, $inner)
$ds = New-Object System.IO.Compression.DeflateStream($ms, [System.IO.Compression.CompressionMode]::Decompress)
$outMs = New-Object System.IO.MemoryStream
$ds.CopyTo($outMs); $ds.Close()
$raw = $outMs.ToArray()

$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
W '// Generated by tools/gen-cc-seed.ps1 - do not edit. Inflated MLow cc_seed protobuf ROM'
W '// (meowcaller mlow/cc_seed.bin, MIT). Parsed + expanded at init by wa_mlow_gains.c.'
W '#include <stdint.h>'
W '#include <stddef.h>'
W ("const int wa_mlow_cc_seed_len = {0};" -f $raw.Length)
W 'const uint8_t wa_mlow_cc_seed[] = {'
$line = '    '
for ($i = 0; $i -lt $raw.Length; $i++) {
    $line += ('{0},' -f $raw[$i])
    if (($i % 20) -eq 19) { W $line; $line = '    ' }
}
if ($line.Trim().Length -gt 0) { W $line }
W '};'
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} inflated bytes)" -f $Out, $raw.Length)
