# Generates core/wa_mlow_pulse_kat.c from meowcaller pulse_vectors.json (frame + subfr[4] + nonzero pulses).
param(
    [Parameter(Mandatory = $true)][string]$Vectors,
    [string]$Out = (Join-Path $PSScriptRoot '..\core\wa_mlow_pulse_kat.c')
)
$ErrorActionPreference = 'Stop'
$v = Get-Content -LiteralPath $Vectors -Raw | ConvertFrom-Json
$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }
W '// Generated by tools/gen-pulse.ps1 - do not edit. MLow pulse KAT (meowcaller pulse_vectors.json, MIT).'
W '#include <stdint.h>'
W ("const int wa_mlow_pulse_kat_len = {0};" -f $v.Count)

$frames = New-Object System.Collections.Generic.List[int]
$frameoff = New-Object System.Collections.Generic.List[int]
$framelen = New-Object System.Collections.Generic.List[int]
$pos = New-Object System.Collections.Generic.List[int]
$val = New-Object System.Collections.Generic.List[int]
$posoff = New-Object System.Collections.Generic.List[int]
$npos = New-Object System.Collections.Generic.List[int]
$subfrLines = New-Object System.Collections.Generic.List[string]
foreach ($rec in $v) {
    $h = $rec.frame; $fl = $h.Length / 2
    $frameoff.Add($frames.Count); $framelen.Add($fl)
    for ($i = 0; $i -lt $fl; $i++) { $frames.Add([Convert]::ToInt32($h.Substring($i*2,2),16)) }
    $subfrLines.Add('{ ' + (($rec.subfr | ForEach-Object { [int]$_ }) -join ',') + ' },')
    $posoff.Add($pos.Count)
    $cnt = 0
    foreach ($p in $rec.pulses) { $pos.Add([int]$p.pos); $val.Add([int]$p.val); $cnt++ }
    $npos.Add($cnt)
}
W ('const int wa_mlow_pulse_kat_framelen[] = { ' + ($framelen -join ',') + ' };')
W ('const int wa_mlow_pulse_kat_frameoff[] = { ' + ($frameoff -join ',') + ' };')
W ('const uint8_t wa_mlow_pulse_kat_frames[] = { ' + ($frames -join ',') + ' };')
W 'const int32_t wa_mlow_pulse_kat_subfr[][4] = {'
foreach ($l in $subfrLines) { W $l }
W '};'
W ('const int wa_mlow_pulse_kat_npos[] = { ' + ($npos -join ',') + ' };')
W ('const int wa_mlow_pulse_kat_posoff[] = { ' + ($posoff -join ',') + ' };')
W ('const int wa_mlow_pulse_kat_pos[] = { ' + ($pos -join ',') + ' };')
W ('const int wa_mlow_pulse_kat_val[] = { ' + ($val -join ',') + ' };')
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1} frames, {2} pulse positions)" -f $Out, $v.Count, $pos.Count)
